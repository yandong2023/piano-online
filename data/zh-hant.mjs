const CHAR_MAP = Object.fromEntries(
  Array.from({ length: PAIRS.length / 2 }, (_, index) => [PAIRS[index * 2], PAIRS[index * 2 + 1]])
);

export function toTraditionalHtml(input) {
  let value = String(input);
  for (const [from, to] of PHRASE_MAP) value = value.replaceAll(from, to);
  return [...value].map((char) => CHAR_MAP[char] || char).join('');
}
